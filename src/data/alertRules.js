export function rulesForCrop(cropId, stageKey) {
  return ALERT_RULES.filter(function (r) {
    if (r.crop !== cropId) return false;
    if (!stageKey || !r.stages) return true;
    return r.stages.indexOf(stageKey) >= 0;
  });
}