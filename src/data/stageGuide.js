function buildAvocado(kind, label) {
  const stages = {};
  STAGE_ORDER.forEach(function (k, i) {
    const base = AV_COMMON[k];
    const days = (AV_FRUIT_DAYS[kind][k]) || base.days || '';
    const pests = AV_PESTS[kind].filter(function (p) { return p.st.indexOf(i + 1) >= 0; })
      .map(function (p) { return { name: p.name, type: p.type }; });
    stages[k] = Object.assign({}, base, { span: AV_SPAN[kind][i], days: days, pests: pests });
  });
  return {
    label: label,
    source: AV_SOURCE,
    seasonNote: 'ฤดูที่พบโรค/แมลงตามบันทึก 2567–2569: รากเน่าโคนเน่า แอนแทรคโนส หนอนเจาะกิ่ง พบได้ตลอดปี (ม.ค.–ธ.ค.) · ใบจุดสาหร่าย ก.ค.–พ.ย. · แมลงวันทอง ' + AV_FLY[kind],
    notes: kind === 'heavy'
      ? ['ไฟล์ระบุช่วงเดือนของระยะ "ชักนำดอก" (พ.ย.–ม.ค.) ทับกับระยะ "แตกใบอ่อน" และอยู่ก่อน "ใบแก่สะสมอาหาร" ซึ่งขัดกับจำนวนวัน แอปจึงใช้ ม.ค. เป็นช่วงชักนำดอก (ก่อนดอกบาน ก.พ.–มี.ค. ประมาณ 30–45 วัน) ถ้าสวนของท่านไม่ตรง ให้ปรับวันเริ่มรอบการผลิต']
      : [],
    stages: stages
  };
}

